-- Aftab Students Book: run this in Supabase Dashboard > SQL Editor.
-- Creates student profiles, study material metadata, RLS and private PDF storage.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create or replace function public.is_aftab_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

-- Prevent users from granting themselves the admin role.
create or replace function public.protect_profile_role()
returns trigger language plpgsql security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and not public.is_aftab_admin() then
    new.role := 'student';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_role_trigger on public.profiles;
create trigger protect_profile_role_trigger
before insert or update on public.profiles
for each row execute function public.protect_profile_role();

alter table public.profiles enable row level security;
drop policy if exists "profile read self or admin" on public.profiles;
create policy "profile read self or admin" on public.profiles
for select to authenticated using (id = auth.uid() or public.is_aftab_admin());
drop policy if exists "profile insert self" on public.profiles;
create policy "profile insert self" on public.profiles
for insert to authenticated with check (id = auth.uid());
drop policy if exists "profile update self or admin" on public.profiles;
create policy "profile update self or admin" on public.profiles
for update to authenticated using (id = auth.uid() or public.is_aftab_admin())
with check (id = auth.uid() or public.is_aftab_admin());

create table if not exists public.study_materials (
  id bigint generated by default as identity primary key,
  title text not null,
  board text not null,
  class_level text,
  course text,
  subject text not null,
  language text not null default 'Hindi',
  material_type text not null default 'Notes',
  description text,
  file_path text,
  is_published boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.study_materials enable row level security;
drop policy if exists "published materials visible to signed in users" on public.study_materials;
create policy "published materials visible to signed in users" on public.study_materials
for select to authenticated using (is_published = true or public.is_aftab_admin());
drop policy if exists "admins insert materials" on public.study_materials;
create policy "admins insert materials" on public.study_materials
for insert to authenticated with check (public.is_aftab_admin());
drop policy if exists "admins update materials" on public.study_materials;
create policy "admins update materials" on public.study_materials
for update to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());
drop policy if exists "admins delete materials" on public.study_materials;
create policy "admins delete materials" on public.study_materials
for delete to authenticated using (public.is_aftab_admin());

-- Private bucket: PDFs are not exposed as public URLs.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('study-pdfs', 'study-pdfs', false, 10485760, array['application/pdf'])
on conflict (id) do update set public = false, file_size_limit = 10485760,
  allowed_mime_types = array['application/pdf'];

drop policy if exists "signed in users read study pdfs" on storage.objects;
create policy "signed in users read study pdfs" on storage.objects
for select to authenticated using (bucket_id = 'study-pdfs');
drop policy if exists "admins upload study pdfs" on storage.objects;
create policy "admins upload study pdfs" on storage.objects
for insert to authenticated with check (bucket_id = 'study-pdfs' and public.is_aftab_admin());
drop policy if exists "admins update study pdfs" on storage.objects;
create policy "admins update study pdfs" on storage.objects
for update to authenticated using (bucket_id = 'study-pdfs' and public.is_aftab_admin())
with check (bucket_id = 'study-pdfs' and public.is_aftab_admin());
drop policy if exists "admins delete study pdfs" on storage.objects;
create policy "admins delete study pdfs" on storage.objects
for delete to authenticated using (bucket_id = 'study-pdfs' and public.is_aftab_admin());

