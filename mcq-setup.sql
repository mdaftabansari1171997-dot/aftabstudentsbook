-- Aftab Students Book: additive MCQ system migration.
-- Run once in Supabase Dashboard > SQL Editor. This does not modify existing study materials or profiles.

create table if not exists public.mcq_quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  board text not null default 'Bihar Board',
  class_level text,
  subject text not null,
  duration_minutes integer not null default 15 check (duration_minutes between 1 and 240),
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.mcq_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.mcq_quizzes(id) on delete cascade,
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_option text not null check (correct_option in ('A','B','C','D')),
  explanation text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.mcq_attempts (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.mcq_quizzes(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  score integer not null default 0,
  total_questions integer not null default 0,
  answers jsonb not null default '[]'::jsonb,
  submitted_at timestamptz not null default now()
);

alter table public.mcq_quizzes enable row level security;
alter table public.mcq_questions enable row level security;
alter table public.mcq_attempts enable row level security;

drop policy if exists "published quizzes visible to authenticated" on public.mcq_quizzes;
create policy "published quizzes visible to authenticated" on public.mcq_quizzes
for select to authenticated using (is_published = true or public.is_aftab_admin());
drop policy if exists "admins manage quizzes" on public.mcq_quizzes;
create policy "admins manage quizzes" on public.mcq_quizzes
for all to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());

drop policy if exists "questions for published quizzes visible" on public.mcq_questions;
create policy "questions for published quizzes visible" on public.mcq_questions
for select to authenticated using (
  exists (select 1 from public.mcq_quizzes q where q.id = quiz_id and (q.is_published = true or public.is_aftab_admin()))
);
drop policy if exists "admins manage questions" on public.mcq_questions;
create policy "admins manage questions" on public.mcq_questions
for all to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());

drop policy if exists "students read own attempts or admin" on public.mcq_attempts;
create policy "students read own attempts or admin" on public.mcq_attempts
for select to authenticated using (student_id = auth.uid() or public.is_aftab_admin());
drop policy if exists "students insert own attempts" on public.mcq_attempts;
create policy "students insert own attempts" on public.mcq_attempts
for insert to authenticated with check (student_id = auth.uid());
drop policy if exists "admins read all attempts" on public.mcq_attempts;
create policy "admins read all attempts" on public.mcq_attempts
for all to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());

create index if not exists mcq_questions_quiz_id_idx on public.mcq_questions(quiz_id, sort_order);
create index if not exists mcq_attempts_student_id_idx on public.mcq_attempts(student_id, submitted_at desc);

-- Server-side scoring: correct answers are never sent to student browsers.
create or replace function public.submit_mcq_attempt(p_quiz_id bigint, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_score integer := 0;
  v_total integer := 0;
  v_details jsonb := '[]'::jsonb;
  v_q record;
  v_selected text;
  v_correct boolean;
  v_attempt_id bigint;
begin
  if v_user is null then
    raise exception 'Please sign in first';
  end if;
  if not exists (select 1 from public.mcq_quizzes where id = p_quiz_id and is_published = true) then
    raise exception 'Quiz is not available';
  end if;
  for v_q in
    select id, correct_option, explanation
    from public.mcq_questions
    where quiz_id = p_quiz_id
    order by sort_order, id
  loop
    v_total := v_total + 1;
    select upper(elem->>'selected') into v_selected
    from jsonb_array_elements(coalesce(p_answers, '[]'::jsonb)) elem
    where (elem->>'question_id')::bigint = v_q.id
    limit 1;
    v_correct := v_selected = v_q.correct_option;
    if v_correct then v_score := v_score + 1; end if;
    v_details := v_details || jsonb_build_array(jsonb_build_object(
      'question_id', v_q.id,
      'selected', v_selected,
      'correct_option', v_q.correct_option,
      'is_correct', v_correct,
      'explanation', coalesce(v_q.explanation, '')
    ));
  end loop;
  if v_total = 0 then raise exception 'This quiz has no questions'; end if;
  insert into public.mcq_attempts(quiz_id, student_id, score, total_questions, answers)
  values(p_quiz_id, v_user, v_score, v_total, v_details)
  returning id into v_attempt_id;
  return jsonb_build_object('attempt_id', v_attempt_id, 'score', v_score, 'total_questions', v_total, 'answers', v_details);
end;
$$;
revoke all on function public.submit_mcq_attempt(bigint, jsonb) from public;
grant execute on function public.submit_mcq_attempt(bigint, jsonb) to authenticated;

-- Expose question text/options to students without exposing the answer key.
create or replace view public.mcq_student_questions
with (security_barrier = true)
as
select q.id, q.quiz_id, q.question_text, q.option_a, q.option_b, q.option_c, q.option_d, q.sort_order
from public.mcq_questions q
join public.mcq_quizzes z on z.id = q.quiz_id
where z.is_published = true;
revoke select on public.mcq_questions from authenticated;
grant insert, update, delete on public.mcq_questions to authenticated;
grant select on public.mcq_student_questions to authenticated;


-- Student profile fields (additive; preserves existing profiles and role values).
alter table public.profiles add column if not exists board text;
alter table public.profiles add column if not exists class_level text;
alter table public.profiles add column if not exists medium text;
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

drop policy if exists "admins can view student profiles" on public.profiles;
create policy "admins can view student profiles"
on public.profiles for select to authenticated
using (public.is_aftab_admin());

-- A student's own profile can be updated, but role is not exposed by the client form.
drop policy if exists "students update own profile" on public.profiles;
create policy "students update own profile"
on public.profiles for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

create or replace function public.get_mcq_leaderboard(p_limit integer default 10)
returns table(student_name text, class_level text, total_score bigint, total_questions bigint, percentage numeric, tests_taken bigint)
language sql
security definer
set search_path = public
as $$
  select coalesce(nullif(p.full_name,''),'Student') as student_name,
         p.class_level,
         sum(a.score)::bigint,
         sum(a.total_questions)::bigint,
         round(100.0 * sum(a.score) / nullif(sum(a.total_questions),0), 2),
         count(*)::bigint
  from public.mcq_attempts a
  join public.profiles p on p.id = a.student_id
  join public.mcq_quizzes q on q.id = a.quiz_id
  where q.is_published = true
  group by p.id, p.full_name, p.class_level
  order by round(100.0 * sum(a.score) / nullif(sum(a.total_questions),0), 2) desc,
           sum(a.score) desc, count(*) desc
  limit greatest(1, least(coalesce(p_limit,10),50));
$$;
revoke all on function public.get_mcq_leaderboard(integer) from public;
grant execute on function public.get_mcq_leaderboard(integer) to authenticated;


-- Prevent a student from changing their own role through profile update APIs.
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role is distinct from old.role and not public.is_aftab_admin() then
    raise exception 'Only an administrator can change profile roles';
  end if;
  return new;
end;
$$;
drop trigger if exists protect_profile_role_trigger on public.profiles;
create trigger protect_profile_role_trigger
before update on public.profiles
for each row execute function public.protect_profile_role();
