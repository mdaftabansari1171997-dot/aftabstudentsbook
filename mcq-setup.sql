-- Aftab Students Book: additive MCQ system migration.
-- Run once in Supabase Dashboard > SQL Editor. This does not modify existing study materials or profiles.

create table if not exists public.mcq_quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  board text not null default 'Bihar Board',
  class_level text,
  subject text not null,
  duration_minutes integer not null default 15 check (duration_minutes between 1 and 240),
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.mcq_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.mcq_quizzes(id) on delete cascade,
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_option text not null check (correct_option in ('A','B','C','D')),
  explanation text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.mcq_attempts (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.mcq_quizzes(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  score integer not null default 0,
  total_questions integer not null default 0,
  answers jsonb not null default '[]'::jsonb,
  submitted_at timestamptz not null default now()
);

alter table public.mcq_quizzes enable row level security;
alter table public.mcq_questions enable row level security;
alter table public.mcq_attempts enable row level security;

drop policy if exists "published quizzes visible to authenticated" on public.mcq_quizzes;
create policy "published quizzes visible to authenticated" on public.mcq_quizzes
for select to authenticated using (is_published = true or public.is_aftab_admin());
drop policy if exists "admins manage quizzes" on public.mcq_quizzes;
create policy "admins manage quizzes" on public.mcq_quizzes
for all to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());

drop policy if exists "questions for published quizzes visible" on public.mcq_questions;
create policy "questions for published quizzes visible" on public.mcq_questions
for select to authenticated using (
  exists (select 1 from public.mcq_quizzes q where q.id = quiz_id and (q.is_published = true or public.is_aftab_admin()))
);
drop policy if exists "admins manage questions" on public.mcq_questions;
create policy "admins manage questions" on public.mcq_questions
for all to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());

drop policy if exists "students read own attempts or admin" on public.mcq_attempts;
create policy "students read own attempts or admin" on public.mcq_attempts
for select to authenticated using (student_id = auth.uid() or public.is_aftab_admin());
drop policy if exists "students insert own attempts" on public.mcq_attempts;
create policy "students insert own attempts" on public.mcq_attempts
for insert to authenticated with check (student_id = auth.uid());
drop policy if exists "admins read all attempts" on public.mcq_attempts;
create policy "admins read all attempts" on public.mcq_attempts
for all to authenticated using (public.is_aftab_admin()) with check (public.is_aftab_admin());

create index if not exists mcq_questions_quiz_id_idx on public.mcq_questions(quiz_id, sort_order);
create index if not exists mcq_attempts_student_id_idx on public.mcq_attempts(student_id, submitted_at desc);
